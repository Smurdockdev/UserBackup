function Test-RealPrinter {
	param ($Printer)
	if (-not $Printer.PortName) { return $false }
	# Exclude known virtual ports
	if ($Printer.PortName -match '^(PORTPROMPT:|FILE:|nul|XPS|PDF)' ) {
		return $false
	}
	# Exclude known virtual drivers
	if ($Printer.DriverName -match 'Microsoft|OneNote|PDF|XPS|Fax') {
		return $false
	}
	return $true
}

function Backup-Printers {
	[CmdletBinding()]
	param (
		[Parameter(Mandatory)]
		[string]$BackupDir
	)
	Write-Host "Printers Export" -ForegroundColor Yellow
	$start   = Get-Date
	$errors  = @()
	$files   = @()
	$success = $true
	try {
		$printers = Get-Printer -ErrorAction Stop |
		Where-Object { Test-RealPrinter $_ } |
			Select-Object `
				Name,
				DriverName,
				PortName,
				ShareName,
				Shared,
				Published,
				ComputerName,
				@{ Name = 'IsDefault'; Expression = { $_.Name -eq (Get-Printer | Where-Object Default).Name } }
		if (-not $printers) {
			Write-Host "  No printers found" -ForegroundColor DarkYellow
			$end = Get-Date
			return [PSCustomObject]@{
				Section      = 'Printers'
				StartTime    = $start
				EndTime      = $end
				DurationSec  = [math]::Round(($end - $start).TotalSeconds,2)
				Success      = $success
				FilesCreated = 0
				Errors       = "No printers found"
			}
		}
		$csvPath = New-BackupFile -Name "Printers" -Extension csv -backupdir $BackupDir
		$txtPath = New-BackupFile -Name "Printers" -Extension txt -backupdir $BackupDir
		$printers | Export-Csv -Path $csvPath -NoTypeInformation
		$files += ($csvPath | measure-object).count
		$printers | Format-Table -AutoSize | Out-File $txtPath
		$files += ($txtPath | measure-object).count
		Write-Host "  Printers exported (CSV + TXT)" -ForegroundColor Green
	} catch {
		$success = $false
		$errors += $_.Exception.Message
	}
	$end = Get-Date
	return [PSCustomObject]@{
		Section      = 'Printers'
		StartTime    = $start
		EndTime      = $end
		DurationSec  = [math]::Round(($end - $start).TotalSeconds,2)
		Success      = $success
		FilesCreated = ($files).count
		Errors       = $errors
	}
}



