function Get-InstalledDrivers {
	[CmdletBinding()]
	param (
		[string[]]$ExcludeManufacturer = @('Microsoft')
	)
	Get-CimInstance Win32_PnPSignedDriver |
		Where-Object {
			$_.DeviceName -and
			$_.DriverVersion -and
			$_.InfName -and
			($ExcludeManufacturer -notcontains $_.Manufacturer)
		} |
		Select-Object `
			DeviceName,
			Manufacturer,
			DriverVersion,
			DriverDate,
			InfName,
			DriverProviderName,
			IsSigned,
			FriendlyName,
			HardwareID
}

function Export-InstalledDrivers {
	[CmdletBinding()]
	param (
		[Parameter(Mandatory)]
		[string]$BackupDir
	)
	$start   = Get-Date
	$errors  = @()
	$files   = @()
