function Compare-SoftwareWithWinget {
	[CmdletBinding()]
	param (		
		[Parameter(Mandatory)]
		[string]$BackupDir
	)
	$start   = Get-Date
	$errors  = @()
	$files   = @()
	$success = $true
	try {
		if (-not (Get-Command winget -ErrorAction SilentlyContinue)) {
			Write-Warning "Winget not available"
			return
		}
		$SoftwareInfoCSV = Get-ChildItem $BackupDir -Filter "$($env:COMPUTERNAME)-InstalledSoftware_*.csv" |
			Sort-Object LastWriteTime -Descending | Select-Object -First 1
		if (-not $SoftwareInfoCSV) {
			Write-Warning "No InstalledSoftware CSV found for Winget comparison"
			return
		} else {
			$software = Import-Csv $SoftwareInfoCSV
		}
		$winget   = winget list --accept-source-agreements --disable-interactivity |
					Select-Object -Skip 1
		$matches = foreach ($app in $software) {
			if ($winget -match [regex]::Escape($app.DisplayName)) {
				[PSCustomObject]@{
					DisplayName = $app.DisplayName
					Publisher   = $app.Publisher
	#				Scope       = $app.Scope
					WingetMatch = $true
				}
			}
		}
		if ($matches) {
			$WingetSoft = New-BackupFile -Name "WingetMatches" -Extension csv -backupdir $BackupDir
			$matches | Export-Csv $WingetSoft -NoTypeInformation
			$files += ($WingetSoft | measure-object).count
			Write-Host "  Winget correlation saved" -ForegroundColor Green
		}
	} catch {
		$success = $false
		$errors += $_.Exception.Message
	}
	$end = Get-Date
	return [PSCustomObject]@{
		Section      = 'WingetCorr'
		StartTime    = $start
		EndTime      = $end
		DurationSec  = [math]::Round(($end - $start).TotalSeconds,2)
		Success      = $success
		FilesCreated = ($files).count
		Errors       = $errors
	}
}


