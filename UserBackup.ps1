function Backup-UserFilesCurrentUserToZip {
	[CmdletBinding()]
	param (
		[Parameter(Mandatory)]
		[string]$BackupDir,

		[Parameter()]
		[string]$ZipName = 'UserFiles.zip'
	)
		$start   = Get-Date
	$errors  = @()
	$files   = @()
	$success = $true
	Write-Host "User Files Backup (Current User)" -ForegroundColor Yellow
	try {
		$zipPath = Join-Path $BackupDir $ZipName
		Remove-Item $zipPath -Force -ErrorAction SilentlyContinue
		$shell = New-Object -ComObject Shell.Application
		$knownFolders = @{
			Desktop    = [Environment]::GetFolderPath('Desktop')
			Documents  = [Environment]::GetFolderPath('MyDocuments')
			Downloads  = $shell.NameSpace('shell:Downloads').Self.Path
			Pictures   = [Environment]::GetFolderPath('MyPictures')
			Favorites  = [Environment]::GetFolderPath('Favorites')
		}
		$pathsToZip = @()
		foreach ($folder in $knownFolders.GetEnumerator()) {
			if ($folder.Value -and (Test-Path $folder.Value)) {
				Write-Host "  Queued: $($folder.Key) -> $($folder.Value)" -ForegroundColor Cyan
				$pathsToZip += $folder.Value
			} else {
				Write-Host "  Skipped: $($folder.Key) (not present)" -ForegroundColor DarkYellow
			}
		}
		if (-not $pathsToZip) {
			Write-Warning "No user folders found to back up"
			return
		}
		Write-Host "Creating ZIP archive..." -ForegroundColor Yellow
		foreach ($path in $pathsToZip) {
			Compress-Archive -Path $path -DestinationPath $zipPath -Update -ErrorAction Stop
			$files += ($path | measure-object).count
		}
	} catch {
		$success = $false
		$errors += $_.Exception.Message
	}
	$end = Get-Date
	Write-Host "  Backup complete: $zipPath" -ForegroundColor Green
	return [PSCustomObject]@{
		Section      = 'UserData'
		StartTime    = $start
		EndTime      = $end
		DurationSec  = [math]::Round(($end - $start).TotalSeconds,2)
		Success      = $success
		FilesCreated = ($files).count
		Errors       = $errors
	}
}



