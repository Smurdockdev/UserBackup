function Invoke-UserBackup {
<#
.SYNOPSIS
Creates a user profile focused backup set including browsers, printers, system info,
networking details, installed software, drivers, and more.

.DESCRIPTION
Invoke-UserBackup is the central backup orchestrator for the Maintenance Toolkit.
It supports two modes:

1. Default (ParameterSet: All)
   Runs every available backup routine and writes results to the specified
   backup directory.

2. Selective (ParameterSet: Selective)
   Allows choosing individual backup components such as browsers, printers,
   networking, installed software, drivers, and more.

If the backup directory does not exist, it is created automatically.

.PARAMETER BackupDir
The directory where all backup output will be stored. The folder will be created
if it does not already exist.

.PARAMETER Browsers
Backs up browser‑related data such as bookmarks and profiles.

.PARAMETER Printers
Exports installed printers and print configuration.

.PARAMETER SystemInfo
Collects system information including OS details, hardware, and environment data.

.PARAMETER MappedDrives
Exports mapped network drives.

.PARAMETER Networking
Backs up networking configuration such as IP settings, adapters, and routes.

.PARAMETER InstalledSoftware
Exports installed software inventory.

.PARAMETER WingetCompare
Generates a comparison between installed software and available Winget packages.

.PARAMETER Drivers
Exports installed driver information.

.PARAMETER UserFiles
Back up user files directly to a ZIP archive. Source folders: Desktop, Documents, Downloads, Pictures, Favorites

.INPUTS
The target directory to store all backup data generated by these functions

.Outputs
Backups of user data, configurations, and files

.EXAMPLE
Invoke-UserBackup -BackupDir "C:\Backups\User01"

Runs a full backup using all available backup modules.

.EXAMPLE
Invoke-UserBackup -BackupDir "D:\Backup" -Selective -InstalledSoftware -Networking

Runs only the InstalledSoftware and Networking backup routines.


.NOTES
Author: Shawn Murdock 2026
Part of the Windows Maintenance Toolkit.
Uses multiple internal backup functions such as Backup-BrowserBookmarks,
Backup-Printers, Backup-SystemInfo, Backup-MappedDrives, Backup-Networking,
Backup-InstalledSoftware, Compare-SoftwareWithWinget, and Export-InstalledDrivers.

#>
	[CmdletBinding(DefaultParameterSetName = 'All')]
	[Alias('ddbu')]
	param (
		[Parameter(Mandatory)]
		[string]$BackupDir,

		[Parameter(ParameterSetName = 'Selective')]
		[switch]$Browsers,

		[Parameter(ParameterSetName = 'Selective')]
		[switch]$Printers,

		[Parameter(ParameterSetName = 'Selective')]
		[switch]$SystemInfo,

		[Parameter(ParameterSetName = 'Selective')]
		[switch]$MappedDrives,

		[Parameter(ParameterSetName = 'Selective')]
		[switch]$Networking,

		[Parameter(ParameterSetName = 'Selective')]
		[switch]$InstalledSoftware,

		[Parameter(ParameterSetName = 'Selective')]
		[switch]$WingetCompare,

		[Parameter(ParameterSetName = 'Selective')]
		[switch]$Drivers,

		[Parameter(ParameterSetName = 'Selective')]
		[switch]$UserFiles
	)
	if ($Host.Name -eq 'ConsoleHost') {Clear-Host}
	Write-Host ""
	Write-Host "Backup Started" -ForegroundColor Cyan
	Write-Host "Backup Path: " -ForegroundColor DarkCyan -NoNewline
	Write-Host $BackupDir -ForegroundColor Green
	Write-Host "---------------------------------------------" -ForegroundColor Blue
	if (-not (Test-Path $BackupDir)) {
		New-Item -ItemType Directory -Path $BackupDir -Force | Out-Null
	}
	$runAll = $PSCmdlet.ParameterSetName -eq 'All'
	$results = [System.Collections.Generic.List[psobject]]::new()
	if ($runAll -or $Browsers) {
			$results += Backup-Chromebm -BackupDir $BackupDir
	}
	if ($runAll -or $Browsers) {
			$results += Backup-Vivaldibm -BackupDir $BackupDir
	}
	if ($runAll -or $Browsers) {
			$results += Backup-Operabm -BackupDir $BackupDir
	}
	if ($runAll -or $Browsers) {
			$results += Backup-Firefoxbm -BackupDir $BackupDir
	}
	if ($runAll -or $Browsers) {
			$results += Backup-Edgebm -BackupDir $BackupDir
	}
	if ($runAll -or $Printers) {
			$results += Backup-Printers -BackupDir $BackupDir
	}
	if ($runAll -or $SystemInfo) {
			$results += Backup-SystemInfo -BackupDir $BackupDir
	}
	if ($runAll -or $InstalledSoftware) {
			$results += Backup-InstalledSoftware -BackupDir $BackupDir
	}
	if ($runAll -or $MappedDrives) {
			$results += Backup-MappedDrives -BackupDir $BackupDir
	}
	if ($runAll -or $Networking) {
			$results += Backup-Networking -BackupDir $BackupDir
	}
	if ($runAll -or $Drivers) {
			$results += Export-InstalledDrivers -BackupDir $BackupDir
	}
	if ($runAll -or $UserFiles) {
			$results += Backup-UserFilesCurrentUserToZip -BackupDir $BackupDir
	}
	if ($runAll -or $WingetCompare) {
			$results += Compare-SoftwareWithWinget -BackupDir $BackupDir
	}
	Write-Host ""

	$results | select Section,DurationSec,Success,Errors,FilesCreated | ft -auto

}

Function Invoke-SelectFolder {
	<#
	.SYNOPSIS
		Open select folder dialog
	.DESCRIPTION
		Open select folder dialog
	.NOTES
		Invoke-SelectFolder | Ver. 2.0 | Shawn Murdock | 2022-10-24
	#>
	[CmdletBinding()]
	[alias('selfldr')]
	Param ([string] $initialDirectory)
	Process {
		Add-Type -AssemblyName System.Windows.Forms
		$FolderBrowserDialog = New-Object System.Windows.Forms.FolderBrowserDialog
		$FolderBrowserDialog.RootFolder = 'MyComputer'
		$FolderBrowserDialog.ShowNewFolderButton = $true
