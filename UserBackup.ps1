function Test-RestorableMappedDrive {
	param ($Drive)
	if (-not $Drive.ProviderName) { return $false }
	if ($Drive.ProviderName -notmatch '^\\\\') { return $false }
	if (-not $Drive.Name) { return $false }
	return $true
}

function Backup-MappedDrives {
	[CmdletBinding()]
	param (
		[Parameter(Mandatory)]
		[string]$BackupDir
	)
	$start   = Get-Date
	$errors  = @()
	$files   = @()
	$success = $true
	Write-Host "Mapped Drive Export" -ForegroundColor Yellow
	try {
		# Active mappings
		$active = Get-CimInstance Win32_MappedLogicalDisk |
			Where-Object { Test-RestorableMappedDrive $_ } |
			Select-Object Name, ProviderName
		# Persistent mappings (HKCU)
		$persistent = Get-ItemProperty 'HKCU:\Network\*' -ErrorAction SilentlyContinue |
			Select-Object `
				@{ Name='Name'; Expression={ $_.PSChildName } },
				@{ Name='ProviderName'; Expression={ $_.RemotePath } }
		$drives = ($active + $persistent) |
			Sort-Object Name, ProviderName -Unique
		if (-not $drives) {
			Write-Host "  No mapped drives found" -ForegroundColor DarkYellow
			return
		}
			$drvsfile = New-BackupFile -Name "MappedDrives" -Extension csv -backupdir $BackupDir
			$drives | Export-Csv $drvsfile -NoTypeInformation
			$files += ($drvsfile | measure-object).count
	} catch {
		$success = $false
		$errors += $_.Exception.Message
	}
	$end = Get-Date
	Write-Host "  Mapped drives exported" -ForegroundColor Green
	return [PSCustomObject]@{
		Section      = 'DrvMappings'
		StartTime    = $start
		EndTime      = $end
		DurationSec  = [math]::Round(($end - $start).TotalSeconds,2)
		Success      = $success
		FilesCreated = ($files).count
		Errors       = $errors
	}	
}


