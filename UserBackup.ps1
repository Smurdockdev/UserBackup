		return $FolderBrowserDialog.SelectedPath
	}
}

function New-BackupFile {
	param(
		[string]$Name,
		[string]$backupdir,
		[string]$Extension = 'txt'
	)
	join-path $backupdir "\$($env:ComputerName)-$($Name)_$(Get-Date -Format 'yyyyMMdd-HHmmss').$Extension"
}

