			New-Item -ItemType Directory -Path $BackupDir -Force -ErrorAction Stop | Out-Null
		}
		$NetConfig = New-BackupFile -Name "Netconfig" -Extension xml -BackupDir $BackupDir
		$NICCfg    = New-BackupFile -Name "NetAdapter" -Extension csv -BackupDir $BackupDir
		$Routes    = New-BackupFile -Name "Routing" -Extension csv -BackupDir $BackupDir
		$IPConfig  = New-BackupFile -Name "IPConfig" -Extension txt -BackupDir $BackupDir
		Get-NetIPConfiguration -ErrorAction Stop | Export-Clixml $NetConfig
		$files += ($NetConfig | measure-object).count
		Get-NetAdapter -ErrorAction Stop |
			Select InterfaceDescription,MacAddress,Status,LinkSpeed,FullDuplex,
				   DriverDescription,DriverVersionString |
			Export-Csv $NICCfg -NoTypeInformation
		$files += ($NICCfg | measure-object).count
		Get-NetRoute -ErrorAction Stop |
			Export-Csv $Routes -NoTypeInformation
		$files += ($Routes | measure-object).count
		ipconfig /all | Out-File $IPConfig -Encoding UTF8
		$files += ($IPConfig | measure-object).count
	} catch {
		$success = $false
		$errors += $_.Exception.Message
	}
	$end = Get-Date
	Write-Host "  Mapped drives exported" -ForegroundColor Green
	return [PSCustomObject]@{
		Section      = 'Networking'
		StartTime    = $start
		EndTime      = $end
		DurationSec  = [math]::Round(($end - $start).TotalSeconds,2)
		Success      = $success
		FilesCreated = ($files).count
		Errors       = $errors
	}
}

