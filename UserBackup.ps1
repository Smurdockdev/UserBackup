 function backup-chromebm {
 	[CmdletBinding()]
	param (
		[Parameter(Mandatory)]
		[string]$BackupDir
	)
	Write-Host "Chrome Bookmarks" -ForegroundColor Yellow
	$start   = Get-Date
	$errors  = @()
	$files   = @()
	$success = $true
	$browserName = 'Chrome'
	$profilename = "Default"
	try {
		if (test-path 'HKLM:\Software\Microsoft\Windows\CurrentVersion\App Paths\chrome.exe'){
			$bookmarkpath = join-path ($($env:LOCALAPPDATA)) "Google\Chrome\User Data\Default\bookmarks"
			if (test-path $bookmarkpath) {
				$dest = Join-Path $BackupDir ("$($env:COMPUTERNAME)-$browserName-$($profile.Name)-Bookmarks-$(Get-Date -Format 'yyyyMMdd-HHmmss').json")
				Copy-Item $bookmarkPath $dest -Force
				Write-Host "  Backed up $($profileName)" -ForegroundColor Green
				$files += ($bookmarkPath | measure-object).count
			} else { 
				Write-Host "  No bookmarks found" -ForegroundColor DarkCyan
				#continue
			}
		} else {
			Write-Host "  $browserName not installed" -ForegroundColor DarkCyan
			#continue
		}
	} catch {
		$success = $false
		$errors += $_.Exception.Message
	}
	$end = Get-Date
	#Write-Host "  $browserName bookmarks backed up" -ForegroundColor Green
	return [PSCustomObject]@{
		Section      = $browserName
		StartTime    = $start
		EndTime      = $end
		DurationSec  = [math]::Round(($end - $start).TotalSeconds,2)
		Success      = $success
		FilesCreated = ($files).count
		Errors       = $errors
	}			
 }

